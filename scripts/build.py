#!/usr/bin/env python3
"""Build Vibe Check from the section files in checklist/.

The section files are the single source of truth. This script:
  1. normalises every section file (header, check count, prev/next links),
  2. regenerates CHECKLIST.md (all sections in one file),
  3. regenerates the GitHub issue template,
  4. updates the contents table and check counts in README.md.

Usage:
  python3 scripts/build.py           # rebuild everything
  python3 scripts/build.py --check   # exit 1 if anything is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECKLIST_DIR = ROOT / "checklist"
THEMES = {"": "Triage", "security": "Security", "launch": "Launch",
          "legal": "Legal", "quality": "Quality"}


def load_sections():
    sections = []
    for path in CHECKLIST_DIR.rglob("*.md"):
        if not re.match(r"^\d{2}-", path.name):
            continue
        text = path.read_text()
        number, title = re.search(r"^# (\d+)\. (.+)$", text, re.M).groups()
        priority = re.search(r"^\*\*Priority:\*\* ([^·\n]+?)\s*(?:·|$)", text, re.M).group(1)
        items = [line for line in text.splitlines() if line.startswith("- [ ] ")]
        # intro = first plain paragraph after the meta line
        body = text.split("\n\n")
        intro = next(p.strip() for p in body[2:] if p.strip()
                     and not p.startswith(("- [ ]", "**Priority", "---", "[", "Previous")))
        folder = path.parent.relative_to(CHECKLIST_DIR).as_posix()
        folder = "" if folder == "." else folder
        sections.append(dict(path=path, number=int(number), title=title, priority=priority,
                             intro=intro, items=items, theme=THEMES[folder]))
    sections.sort(key=lambda s: s["number"])
    return sections


def rel(from_path, to_path):
    import os
    return os.path.relpath(to_path, from_path.parent).replace(os.sep, "/")


def render_section(s, prev, nxt):
    readme = ROOT / "README.md"
    nav = []
    nav.append(f"Previous: [{prev['number']}. {prev['title']}]({rel(s['path'], prev['path'])})" if prev else "Previous: none")
    nav.append(f"[All sections]({rel(s['path'], readme)}#contents)")
    nav.append(f"Next: [{nxt['number']}. {nxt['title']}]({rel(s['path'], nxt['path'])})" if nxt else "Next: none")
    return (f"# {s['number']}. {s['title']}\n\n"
            f"**Priority:** {s['priority']} · **Theme:** {s['theme']} · **Checks:** {len(s['items'])}\n\n"
            f"{s['intro']}\n\n" + "\n".join(s["items"]) + "\n\n---\n\n" + " · ".join(nav) + "\n")


def render_full(sections, header):
    out = [header]
    for s in sections:
        out.append(f"## {s['number']}. {s['title']}\n\n"
                   f"**Priority:** {s['priority']} · **Checks:** {len(s['items'])}\n\n"
                   f"{s['intro']}\n\n" + "\n".join(s["items"]) + "\n")
    return "\n".join(out)


def render_contents(sections):
    rows = ["| # | Section | Theme | Priority | Checks |", "|---|---|---|---|---|"]
    for s in sections:
        link = s["path"].relative_to(ROOT).as_posix()
        rows.append(f"| {s['number']} | [{s['title']}]({link}) | {s['theme']} | {s['priority']} | {len(s['items'])} |")
    return "\n".join(rows)


def build():
    sections = load_sections()
    total = sum(len(s["items"]) for s in sections)
    files = {}

    for i, s in enumerate(sections):
        prev = sections[i - 1] if i > 0 else None
        nxt = sections[i + 1] if i + 1 < len(sections) else None
        files[s["path"]] = render_section(s, prev, nxt)

    files[ROOT / "CHECKLIST.md"] = render_full(sections,
        "# Vibe Check: the full checklist\n\n"
        "By Kthuwu. Licensed under CC BY 4.0.\n\n"
        f"All {total} checks in one file. Copy it into your project and tick as you go.\n\n"
        "> Generated by `scripts/build.py` from the files in `checklist/`. Edit those, not this.\n\n"
        "**Project:** ________ · **Reviewed by:** ________ · **Date:** ________\n")

    files[ROOT / ".github/ISSUE_TEMPLATE/launch-audit.md"] = render_full(sections,
        "---\nname: Launch audit\nabout: Run the full Vibe Check against a project\n"
        "title: \"Launch audit: <project>\"\nlabels: audit\n---\n\n"
        f"Work through all {total} checks. Tick what passes, and leave a comment on anything that fails.\n")

    readme = (ROOT / "README.md").read_text()
    readme = re.sub(r"(<!-- contents:start -->\n).*?(<!-- contents:end -->)",
                    lambda m: m.group(1) + render_contents(sections) + "\n" + m.group(2), readme, flags=re.S)
    readme = re.sub(r"<!-- total -->\d+<!-- /total -->", f"<!-- total -->{total}<!-- /total -->", readme)
    readme = re.sub(r"<!-- sections -->\d+<!-- /sections -->",
                    f"<!-- sections -->{len(sections)}<!-- /sections -->", readme)
    files[ROOT / "README.md"] = readme
    return files, total, len(sections)


def main():
    files, total, count = build()
    stale = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
    if "--check" in sys.argv:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c)
    print(f"Built {total} checks across {count} sections ({len(stale)} files changed)")


if __name__ == "__main__":
    main()
